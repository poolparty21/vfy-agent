// Poseidon over BN254 Fr — the exact permutation the vfy-policy circuit uses.
//
// WHY THIS IS NOT "JUST A HASH"
//
// The Steal the VFY circuit derives the agent's commitment IN CIRCUIT:
//
//     commitment = Poseidon(strategyParams[0..7], salt)   // params first, salt last
//
// so a commitment produced by any other primitive (the old keccak256(W || R))
// has no witness at all and every turn goes out unproved: −2 per turn. That is
// exactly what happened to the 13–17 Nov Swiss stage.
//
// Poseidon(9) here is circomlib's Poseidon with nine inputs, which means:
//
//     t = 9 + 1 = 10, nRoundsF = 8, nRoundsP = 60 (circomlib N_ROUNDS_P[8])
//
// The round constants and the MDS matrix are circomlib's (generated by its
// reference Grain script) and live in poseidon-t10.json as data. They are NOT
// hand-typed: the table was generated once from circomlibjs, and
// test/poseidon.test.js pins vectors produced by circomlibjs itself, so a
// mistyped constant or a wrong round count fails the unit test instead of
// silently costing a match.
//
// The stronger check is `prover/check-vfy-turn.mjs`: it builds a witness for a
// turn, generates a real Groth16 proof and verifies it against the platform's
// published vfy-policy zkey. A hash that is off by one round cannot pass that.
//
// No dependencies: this file reads its constants and runs on Node 20+, which
// keeps the commitment reproducible on any machine with the repo.
import { readFileSync } from "node:fs";

/** BN254 scalar field modulus (the circuit's field). */
export const FIELD = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;

const doc = JSON.parse(readFileSync(new URL("./poseidon-t10.json", import.meta.url), "utf8"));
const T = doc.t;
const ROUNDS_F = doc.nRoundsF;
const ROUNDS_P = doc.nRoundsP;
const ROUNDS = ROUNDS_F + ROUNDS_P;

if (T !== 10 || ROUNDS_F !== 8) throw new Error("poseidon-t10.json: unexpected parameters");
if (!Array.isArray(doc.C) || doc.C.length !== ROUNDS * T) {
  throw new Error(`poseidon-t10.json: expected ${ROUNDS * T} round constants, got ${doc.C?.length}`);
}
if (!Array.isArray(doc.M) || doc.M.length !== T || doc.M.some((row) => row.length !== T)) {
  throw new Error("poseidon-t10.json: expected a 10x10 MDS matrix");
}

const C = doc.C.map((v) => BigInt(v));
const M = doc.M.map((row) => row.map((v) => BigInt(v)));

/** Reduce into the field, keeping the result non-negative. */
const mod = (x) => {
  const r = x % FIELD;
  return r < 0n ? r + FIELD : r;
};

const pow5 = (a) => {
  const a2 = (a * a) % FIELD;
  return (((a2 * a2) % FIELD) * a) % FIELD;
};

/**
 * Poseidon with nine inputs (t = 10), returning the first state word.
 *
 * The state is [capacity, x0..x8]: index 0 is the capacity element (zero), and
 * the nine inputs follow in order. The round pattern is circomlib's: 4 full
 * rounds, 60 partial rounds (S-box on state[0] only), 4 full rounds, each round
 * adding its constants and multiplying by the MDS matrix.
 *
 * @param {Array<bigint|number|string>} inputs exactly nine values
 * @returns {bigint} the digest, reduced into the field
 */
export function poseidon(inputs) {
  if (!Array.isArray(inputs) || inputs.length !== 9) {
    throw new Error(`poseidon: expected exactly 9 inputs, got ${inputs?.length}`);
  }

  let state = new Array(T).fill(0n);
  for (let i = 0; i < 9; i++) state[i + 1] = mod(BigInt(inputs[i]));

  for (let r = 0; r < ROUNDS; r++) {
    for (let i = 0; i < T; i++) state[i] = mod(state[i] + C[r * T + i]);

    if (r < ROUNDS_F / 2 || r >= ROUNDS_F / 2 + ROUNDS_P) {
      for (let i = 0; i < T; i++) state[i] = pow5(state[i]);
    } else {
      state[0] = pow5(state[0]);
    }

    const next = new Array(T);
    for (let i = 0; i < T; i++) {
      const row = M[i];
      let acc = 0n;
      for (let j = 0; j < T; j++) acc += row[j] * state[j];
      next[i] = mod(acc);
    }
    state = next;
  }

  return state[0];
}

/**
 * The commitment the circuit checks: Poseidon(strategyParams[0..7], salt).
 *
 * @param {Array<bigint|number|string>} params the eight committed strategy params
 * @param {bigint|number|string} salt      the private salt
 * @returns {bigint}
 */
export function strategyCommitment(params, salt) {
  const list = [...(params ?? [])];
  if (list.length !== 8) throw new Error(`strategyParams must be exactly 8 values, got ${list.length}`);
  if (salt === undefined || salt === null || salt === "") throw new Error("salt is required");
  return poseidon([...list.map((v) => mod(BigInt(v))), mod(BigInt(salt))]);
}

/** 32-byte, 0x-prefixed hex — the shape the dashboard stores. */
export const toHex32 = (v) => "0x" + BigInt(v).toString(16).padStart(64, "0");

/** Parse the salt from env or the gitignored `.strategy-salt` file. */
export function parseSalt(raw) {
  const text = String(raw ?? "").trim();
  if (!/^(0x)?[0-9a-fA-F]+$/.test(text)) throw new Error("salt must be hex");
  return BigInt(text.startsWith("0x") || text.startsWith("0X") ? text : "0x" + text);
}

/** Parse "10,0,0,0,0,0,0,0" into the eight strategy params. */
export function parseStrategyParams(raw) {
  const parts = String(raw ?? "").split(",").map((s) => s.trim()).filter(Boolean);
  if (parts.length !== 8) throw new Error(`STRATEGY_PARAMS must be 8 comma-separated integers, got ${parts.length}`);
  return parts.map((v) => BigInt(v));
}
